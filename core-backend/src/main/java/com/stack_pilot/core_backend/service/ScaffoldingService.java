package com.stack_pilot.core_backend.service;

import org.springframework.stereotype.Service;

import java.util.HashSet;
import java.util.List;
import java.util.Set;
import java.util.stream.Collectors;

@Service
public class ScaffoldingService {

    public String generateDockerCompose(List<String> rawComponents) {
        if (rawComponents == null || rawComponents.isEmpty()) {
            return "version: '3.8'\n\nservices: {}\n";
        }

        Set<String> comps = rawComponents.stream()
                .map(String::toLowerCase)
                .map(String::trim)
                .collect(Collectors.toSet());

        StringBuilder sb = new StringBuilder();
        Set<String> volumes = new HashSet<>();

        sb.append("# Generated by StackPilot Architectural Engine\n");
        sb.append("version: '3.8'\n\nservices:\n");

        if (comps.contains("postgresql")) {
            volumes.add("pgdata");
            sb.append("  postgres:\n")
              .append("    image: postgres:16-alpine\n")
              .append("    container_name: stackpilot_postgres\n")
              .append("    restart: unless-stopped\n")
              .append("    environment:\n")
              .append("      POSTGRES_USER: ${POSTGRES_USER:-postgres}\n")
              .append("      POSTGRES_PASSWORD: ${POSTGRES_PASSWORD:-postgres}\n")
              .append("      POSTGRES_DB: ${POSTGRES_DB:-stackpilot_app}\n")
              .append("    ports:\n")
              .append("      - '5432:5432'\n")
              .append("    volumes:\n")
              .append("      - pgdata:/var/lib/postgresql/data\n")
              .append("    networks:\n")
              .append("      - stackpilot_net\n\n");
        }

        if (comps.contains("mysql")) {
            volumes.add("mysqldata");
            sb.append("  mysql:\n")
              .append("    image: mysql:8.0\n")
              .append("    container_name: stackpilot_mysql\n")
              .append("    restart: unless-stopped\n")
              .append("    environment:\n")
              .append("      MYSQL_ROOT_PASSWORD: ${MYSQL_ROOT_PASSWORD:-rootpassword}\n")
              .append("      MYSQL_DATABASE: ${MYSQL_DATABASE:-stackpilot_app}\n")
              .append("    ports:\n")
              .append("      - '3306:3306'\n")
              .append("    volumes:\n")
              .append("      - mysqldata:/var/lib/mysql\n")
              .append("    networks:\n")
              .append("      - stackpilot_net\n\n");
        }

        if (comps.contains("mongodb")) {
            volumes.add("mongodata");
            sb.append("  mongodb:\n")
              .append("    image: mongo:7.0\n")
              .append("    container_name: stackpilot_mongodb\n")
              .append("    restart: unless-stopped\n")
              .append("    ports:\n")
              .append("      - '27017:27017'\n")
              .append("    volumes:\n")
              .append("      - mongodata:/data/db\n")
              .append("    networks:\n")
              .append("      - stackpilot_net\n\n");
        }

        if (comps.contains("redis")) {
            volumes.add("redisdata");
            sb.append("  redis:\n")
              .append("    image: redis:7-alpine\n")
              .append("    container_name: stackpilot_redis\n")
              .append("    restart: unless-stopped\n")
              .append("    ports:\n")
              .append("      - '6379:6379'\n")
              .append("    volumes:\n")
              .append("      - redisdata:/data\n")
              .append("    networks:\n")
              .append("      - stackpilot_net\n\n");
        }

        if (comps.contains("rabbitmq")) {
            volumes.add("rabbitmqdata");
            sb.append("  rabbitmq:\n")
              .append("    image: rabbitmq:3-management-alpine\n")
              .append("    container_name: stackpilot_rabbitmq\n")
              .append("    restart: unless-stopped\n")
              .append("    ports:\n")
              .append("      - '5672:5672'\n")
              .append("      - '15672:15672'\n")
              .append("    volumes:\n")
              .append("      - rabbitmqdata:/var/lib/rabbitmq\n")
              .append("    networks:\n")
              .append("      - stackpilot_net\n\n");
        }

        if (comps.contains("kafka")) {
            sb.append("  kafka:\n")
              .append("    image: apache/kafka:latest\n")
              .append("    container_name: stackpilot_kafka\n")
              .append("    restart: unless-stopped\n")
              .append("    environment:\n")
              .append("      KAFKA_NODE_ID: 1\n")
              .append("      KAFKA_PROCESS_ROLES: broker,controller\n")
              .append("      KAFKA_LISTENERS: PLAINTEXT://:9092,CONTROLLER://:9093\n")
              .append("      KAFKA_ADVERTISED_LISTENERS: PLAINTEXT://localhost:9092\n")
              .append("      KAFKA_CONTROLLER_LISTENER_NAMES: CONTROLLER\n")
              .append("      KAFKA_CONTROLLER_QUORUM_VOTERS: 1@localhost:9093\n")
              .append("    ports:\n")
              .append("      - '9092:9092'\n")
              .append("    networks:\n")
              .append("      - stackpilot_net\n\n");
        }

        if (comps.contains("prometheus")) {
            sb.append("  prometheus:\n")
              .append("    image: prom/prometheus:latest\n")
              .append("    container_name: stackpilot_prometheus\n")
              .append("    restart: unless-stopped\n")
              .append("    ports:\n")
              .append("      - '9090:9090'\n")
              .append("    networks:\n")
              .append("      - stackpilot_net\n\n");
        }

        if (comps.contains("grafana")) {
            volumes.add("grafanadata");
            sb.append("  grafana:\n")
              .append("    image: grafana/grafana:latest\n")
              .append("    container_name: stackpilot_grafana\n")
              .append("    restart: unless-stopped\n")
              .append("    ports:\n")
              .append("      - '3000:3000'\n")
              .append("    volumes:\n")
              .append("      - grafanadata:/var/lib/grafana\n")
              .append("    networks:\n")
              .append("      - stackpilot_net\n\n");
        }

        if (comps.contains("elasticsearch")) {
            volumes.add("esdata");
            sb.append("  elasticsearch:\n")
              .append("    image: elasticsearch:8.11.0\n")
              .append("    container_name: stackpilot_elasticsearch\n")
              .append("    restart: unless-stopped\n")
              .append("    environment:\n")
              .append("      - discovery.type=single-node\n")
              .append("      - xpack.security.enabled=false\n")
              .append("    ports:\n")
              .append("      - '9200:9200'\n")
              .append("    volumes:\n")
              .append("      - esdata:/usr/share/elasticsearch/data\n")
              .append("    networks:\n")
              .append("      - stackpilot_net\n\n");
        }

        if (!volumes.isEmpty()) {
            sb.append("volumes:\n");
            for (String vol : volumes) {
                sb.append("  ").append(vol).append(":\n");
            }
            sb.append("\n");
        }

        sb.append("networks:\n  stackpilot_net:\n    driver: bridge\n");
        return sb.toString();
    }

    public String generateEnvExample(List<String> rawComponents) {
        if (rawComponents == null || rawComponents.isEmpty()) {
            return "# StackPilot Environment Configuration\n";
        }

        Set<String> comps = rawComponents.stream()
                .map(String::toLowerCase)
                .map(String::trim)
                .collect(Collectors.toSet());

        StringBuilder sb = new StringBuilder();
        sb.append("# ==========================================================\n");
        sb.append("# StackPilot Generated Environment Configuration\n");
        sb.append("# ==========================================================\n\n");

        if (comps.contains("postgresql")) {
            sb.append("# PostgreSQL Database\n")
              .append("DATABASE_URL=postgresql://postgres:postgres@localhost:5432/stackpilot_app\n")
              .append("POSTGRES_USER=postgres\n")
              .append("POSTGRES_PASSWORD=postgres\n")
              .append("POSTGRES_DB=stackpilot_app\n\n");
        }

        if (comps.contains("mysql")) {
            sb.append("# MySQL Database\n")
              .append("DATABASE_URL=mysql://root:rootpassword@localhost:3306/stackpilot_app\n")
              .append("MYSQL_ROOT_PASSWORD=rootpassword\n")
              .append("MYSQL_DATABASE=stackpilot_app\n\n");
        }

        if (comps.contains("mongodb")) {
            sb.append("# MongoDB\n")
              .append("MONGODB_URI=mongodb://localhost:27017/stackpilot_app\n\n");
        }

        if (comps.contains("redis")) {
            sb.append("# Redis Cache / Message Broker\n")
              .append("REDIS_URL=redis://localhost:6379/0\n\n");
        }

        if (comps.contains("rabbitmq")) {
            sb.append("# RabbitMQ\n")
              .append("RABBITMQ_URI=amqp://guest:guest@localhost:5672/\n")
              .append("RABBITMQ_MANAGEMENT_URL=http://localhost:15672\n\n");
        }

        if (comps.contains("kafka")) {
            sb.append("# Apache Kafka\n")
              .append("KAFKA_BOOTSTRAP_SERVERS=localhost:9092\n\n");
        }

        if (comps.contains("elasticsearch")) {
            sb.append("# Elasticsearch\n")
              .append("ELASTICSEARCH_URL=http://localhost:9200\n\n");
        }

        if (comps.contains("sentry")) {
            sb.append("# Sentry Error Tracking\n")
              .append("SENTRY_DSN=https://examplePublicKey@o0.ingest.sentry.io/0\n")
              .append("SENTRY_ENVIRONMENT=development\n\n");
        }

        if (comps.contains("stripe")) {
            sb.append("# Stripe Payments\n")
              .append("STRIPE_SECRET_KEY=sk_test_51MockKey\n")
              .append("STRIPE_WEBHOOK_SECRET=whsec_MockWebhookSecret\n\n");
        }

        return sb.toString();
    }
}
